/** الذكاء يكتب Markdown بسيط؛ نعرضه نص مرتب: بدون رموز، والنقاط «•». */
export function assistantDisplayText(raw: string): string {
  return raw
    .replace(/\r\n/g, '\n')
    .split('\n')
    .map((line) =>
      line
        .replace(/\*\*|__|`/g, '')
        .replace(/^(\s*)#{1,6}\s+/, '$1')
        .replace(/^(\s*)[*\-+]\s+/, '$1• ')
        .trimEnd(),
    )
    .join('\n')
    .replace(/\n{3,}/g, '\n\n')
    .trim();
}
