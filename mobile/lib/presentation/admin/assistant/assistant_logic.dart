/// الذكاء يكتب Markdown بسيط (**غامق**، # عنوان، * نقطة). التطبيق يعرض نص عادي مرتب بدل مكتبة Markdown
/// (حتى ما يثقل): نشيل الرموز ونحوّل النقاط لـ «•».
String assistantDisplayText(String raw) {
  final lines = raw.replaceAll('\r\n', '\n').split('\n').map((line) {
    var l = line.replaceAll('**', '').replaceAll('__', '').replaceAll('`', '');
    l = l.replaceFirstMapped(RegExp(r'^(\s*)#{1,6}\s+'), (m) => m[1]!);
    l = l.replaceFirstMapped(RegExp(r'^(\s*)[*\-+]\s+'), (m) => '${m[1]}• ');
    return l.trimRight();
  });
  return lines.join('\n').replaceAll(RegExp(r'\n{3,}'), '\n\n').trim();
}
